export interface ExportPayload {
  title: string;
  persona: string;
  question: string;
  answer: string;
}

function download(blob: Blob, filename: string) {
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 2000);
}

const stamp = () => new Date().toISOString().slice(0, 19).replace(/[:T]/g, "-");

export function exportMarkdown(p: ExportPayload) {
  const md = `# ${p.title}\n\n_Generated by ${p.persona} · Gemma3-1B-IT (LiteRT int4, local, in-browser) · ${new Date().toLocaleString()}_\n\n## Question\n\n${p.question}\n\n## Answer\n\n${p.answer}\n`;
  download(new Blob([md], { type: "text/markdown;charset=utf-8" }), `response-${stamp()}.md`);
}

export async function exportPdf(p: ExportPayload) {
  const { jsPDF } = await import("jspdf");
  const doc = new jsPDF({ unit: "pt", format: "a4" });
  const margin = 48;
  const width = doc.internal.pageSize.getWidth() - margin * 2;
  const pageH = doc.internal.pageSize.getHeight();
  let y = margin;

  const write = (text: string, size: number, bold = false, color = 20) => {
    doc.setFont("helvetica", bold ? "bold" : "normal");
    doc.setFontSize(size);
    doc.setTextColor(color);
    const lines = doc.splitTextToSize(text, width) as string[];
    for (const line of lines) {
      if (y > pageH - margin) {
        doc.addPage();
        y = margin;
      }
      doc.text(line, margin, y);
      y += size * 1.45;
    }
    y += size * 0.5;
  };

  write(p.title, 20, true);
  write(`Generated by ${p.persona} · Gemma3-1B-IT (LiteRT int4, local, in-browser) · ${new Date().toLocaleString()}`, 9, false, 110);
  write("QUESTION", 10, true, 80);
  write(p.question, 12);
  write("ANSWER", 10, true, 80);
  write(p.answer.replace(/[^\x00-\xFF]/g, "?"), 12);
  doc.save(`response-${stamp()}.pdf`);
}

export async function exportDocx(p: ExportPayload) {
  const { Document, Packer, Paragraph, TextRun, HeadingLevel } = await import("docx");
  const paras = (text: string) =>
    text.split(/\n+/).map((line) => new Paragraph({ children: [new TextRun({ text: line, size: 24 })], spacing: { after: 140 } }));
  const doc = new Document({
    sections: [
      {
        children: [
          new Paragraph({ text: p.title, heading: HeadingLevel.TITLE }),
          new Paragraph({
            children: [
              new TextRun({
                text: `Generated by ${p.persona} · Gemma3-1B-IT (LiteRT int4, local, in-browser) · ${new Date().toLocaleString()}`,
                italics: true,
                size: 18,
                color: "666666",
              }),
            ],
            spacing: { after: 240 },
          }),
          new Paragraph({ text: "Question", heading: HeadingLevel.HEADING_2 }),
          ...paras(p.question),
          new Paragraph({ text: "Answer", heading: HeadingLevel.HEADING_2 }),
          ...paras(p.answer),
        ],
      },
    ],
  });
  const blob = await Packer.toBlob(doc);
  download(blob, `response-${stamp()}.docx`);
}
